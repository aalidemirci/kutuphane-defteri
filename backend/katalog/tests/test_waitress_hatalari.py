"""TB11 — waitress'in kendi hata yanıtları Türkçe ve CSP'li (gerçek waitress ile).

İstek uygulamaya hiç ulaşmadan reddedildiğinde (bozuk istek satırı, büyük
başlık, büyük gövde) yanıtı waitress üretir. `katalog.waitress_hatalari.uygula`
sunucu örneğinin kanal sınıfını değiştirir; burada gerçek bir waitress
sunucusu loopback'te kurulur ve ham soketle kötü istekler gönderilir.
"""

from __future__ import annotations

import socket
import threading
from collections.abc import Iterator
from typing import Any

import pytest
from waitress.channel import HTTPChannel  # type: ignore[import-untyped]
from waitress.server import create_server  # type: ignore[import-untyped]

from katalog import app as katalog_app
